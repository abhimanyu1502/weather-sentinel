export const SUBDISTRICT_COUNT = ALL_SUBDISTRICTS.length;

export function subdistrictById(id: string): Subdistrict | undefined {
  return ALL_SUBDISTRICTS.find((s) => s.id === id);
}

/**
 * Converts a subdistrict to a navigable City interface object
 * so that any nowcast, 3km perimeter, and pin operates seamlessly.
 */
export function subdistrictToCity(sd: Subdistrict): import("./indiaGeo").City {
  return {
    id: sd.id,
    name: `${sd.name} (${sd.parentCityName})`,
    state: sd.state,
    lat: sd.lat,
    lon: sd.lon,
    type: "major",
    population_m: 0.15,
  };
}
